describe('E2E: Навігація сайтом', () => {
  it('відкриває головну сторінку та переходить до каталогу курсів', () => {
    // 1. Заходимо на головну сторінку
    cy.visit('/');

    // 2. Перевіряємо, чи є там головний заголовок
    cy.contains('Системне вивчення ІТ').should('be.visible');

    // 3. Клікаємо на кнопку "Обрати курс" (або на лінк в навігації)
    cy.contains('Обрати курс').click();

    // 4. Перевіряємо, чи змінився URL і чи ми на сторінці курсів
    cy.url().should('include', '/courses');
    cy.contains('Каталог курсів').should('be.visible');
  });
});
